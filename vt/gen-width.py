#!/usr/bin/env python3
"""Writes src/Vt/Width.geng: the codepoint ranges that take two cells and
those that take none, as the oracle lays text out: harness/oracle/widths
prints libghostty-vt's ghostty_unicode_codepoint_width, its own table (uucode's
wcwidth from UCD 18.0.0), so that the two agree (docs/vt-core.md §VC17). They
were Python's unicodedata (15.0.0) at first, for the probe's cost only, and
differed: U+4DC0 to U+4DFF are wide since Unicode 16. A code point up to 0xFF
takes one cell, as Ghostty prints it whatever its table says (U+00AD).

And the Extended_Pictographic ranges, less Emoji_Modifier_Base, which VS15
and VS16 need before them, from the emoji-data.txt of the same UCD.

Needs harness/oracle/build.sh first.

usage: gen-width.py > src/Vt/Width.geng && ../scripts/fmt.sh src/Vt/Width.geng
"""
import glob
import os
import subprocess
import sys

WIDTHS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../harness/oracle/widths")

EMOJI = glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                               "../vendor/ghostty/zig-pkg/uucode-0.2.0-ZZjBPoGFVgCiflJNFc6Io8xzC67B6PA5bUkk4LT0kCxg/ucd/emoji/emoji-data.txt"))[0]


def emoji_property(name):
    cps = set()
    for line in open(EMOJI):
        line = line.split("#")[0].strip()
        if not line:
            continue
        span, prop = (x.strip() for x in line.split(";"))
        if prop != name:
            continue
        a, _, b = span.partition("..")
        cps.update(range(int(a, 16), int(b or a, 16) + 1))
    return cps


def pictographic():
    """Extended_Pictographic but not Emoji_Modifier_Base: uucode's
    grapheme_break gives a modifier base a value of its own, so Ghostty's
    test for `.extended_pictographic` is false for one (U+270C, U+1F44D)."""
    cps = emoji_property("Extended_Pictographic") - emoji_property("Emoji_Modifier_Base")
    merged = []
    for cp in sorted(cps):
        if merged and cp == merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], cp)
        else:
            merged.append((cp, cp))
    return merged


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and cp == out[-1][1] + 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def emoji_version():
    for line in open(EMOJI):
        if line.startswith("# Version:"):
            return line.split(":")[1].strip()
    return "?"


def oracle():
    two, zero = set(), set()
    for line in subprocess.run([WIDTHS], capture_output=True, text=True, check=True).stdout.split("\n"):
        if line:
            cp, w = line.split()
            (two if w == "2" else zero).add(int(cp, 16))
    return two, zero


two, zero = oracle()
wide = ranges(two)
none = ranges(zero)
picto = pictographic()


def table():
    """Every codepoint below U+20000 as 2 bits, sixteen to a 32-bit word: 1
    unless a zero-width range says 0 or a wide one 2, wide over zero, as the
    search asks wide first. A word is written signed, since Int is 32 bits."""
    w = [1] * 0x20000
    for a, b in none:
        for cp in range(a, min(b, 0x1FFFF) + 1):
            w[cp] = 0
    for a, b in wide:
        for cp in range(a, min(b, 0x1FFFF) + 1):
            w[cp] = 2
    out = []
    for k in range(0, 0x20000, 16):
        v = 0
        for j in range(16):
            v |= w[k + j] << (2 * j)
        out.append(v - (1 << 32) if v >= 1 << 31 else v)
    return out


def arr(name, xs):
    body = "\n    , ".join(str(x) for x in xs)
    return f"{name} : Array Int\n{name} =\n    [ {body}\n    ]\n"


print(f"""module Vt.Width exposing (width, pictographic)

{{-| Generated by vt/gen-width.py from libghostty-vt's widths: do not edit.
{len(wide)} wide ranges and {len(none)} zero-width ranges, and {len(picto)}
ranges of Extended_Pictographic but not Emoji_Modifier_Base from
emoji-data.txt {emoji_version()}. Below U+20000 a
codepoint's width is two bits of `table` (geng-lang `m4-puritty.md` §VA15.6's
P3, a literal here so that nothing builds it at run time); above, a binary
search of the ranges. -}}

import Bitwise


{{-| How many cells a codepoint at or above 0x80 takes: 0, 1 or 2. -}}
width : Int -> Int
width cp =
    if cp < 0x20000 then
        when Array.get (Bitwise.shiftRightZfBy 4 cp) table is
            Just word ->
                Bitwise.and 3 (Bitwise.shiftRightZfBy (2 * Bitwise.and 15 cp) word)

            Nothing ->
                1

    else
        searched cp


searched : Int -> Int
searched cp =
    if find wideStarts wideEnds cp 0 (Array.length wideStarts - 1) then
        2

    else if find noneStarts noneEnds cp 0 (Array.length noneStarts - 1) then
        0

    else
        1


find : Array Int -> Array Int -> Int -> Int -> Int -> Bool
find starts ends cp lo hi =
    if lo > hi then
        False

    else
        let
            mid =
                (lo + hi) // 2

            s =
                Maybe.withDefault 0 (Array.get mid starts)
        in
        if cp < s then
            find starts ends cp lo (mid - 1)

        else if cp > Maybe.withDefault 0 (Array.get mid ends) then
            find starts ends cp (mid + 1) hi

        else
            True


{{-| Whether a codepoint is Extended_Pictographic and not an
Emoji_Modifier_Base: what VS15 and VS16 may follow, as Ghostty reads its
grapheme break property. -}}
pictographic : Int -> Bool
pictographic cp =
    find pictoStarts pictoEnds cp 0 (Array.length pictoStarts - 1)

""")
print(arr("table", table()))
print()
print(arr("wideStarts", [a for a, _ in wide]))
print()
print(arr("wideEnds", [b for _, b in wide]))
print()
print(arr("noneStarts", [a for a, _ in none]))
print()
print(arr("noneEnds", [b for _, b in none]))
print()
print(arr("pictoStarts", [a for a, _ in picto]))
print()
print(arr("pictoEnds", [b for _, b in picto]))
