#!/usr/bin/env python3
"""Writes src/Vt/KeyTables.geng from libghostty-vt's sources (vendor/ghostty,
the oracle's v1.4.0), the tables Vt.Keys encodes with (docs/phase3-input.md
V47):

  - every key, numbered as Ghostty's `input.Key` (and so `GhosttyKey`) is,
    as a constant `key` + its name in camel case;
  - `codepoint`: the code point a key stands for (`Key.codepoint`), 0 for none;
  - `kittyCode`, `kittyFinal`, `kittyModifier`: kitty.zig's entries by key,
    0 for a key with none;
  - `evdevKey`: the key for each evdev code, from keycodes.zig's table
    (Chromium's), by its W3C code.
"""
import pathlib, re

here = pathlib.Path(__file__).parent
g = here / "../vendor/ghostty/src/input"
key_zig = (g / "key.zig").read_text()

body = key_zig[key_zig.index("pub const Key = enum(c_int) {"):]
body = body[body.index("{") + 1:]
names = []
for line in body.splitlines():
    line = line.split("//")[0].strip()
    if not line:
        continue
    if line.startswith("pub fn") or line.startswith("const") or line.startswith("};"):
        break
    m = re.fullmatch(r'(?:@")?([a-z0-9_]+)"?,', line)
    if m:
        names.append(m.group(1))
index = {n: i for i, n in enumerate(names)}

def camel(n):
    parts = n.split("_")
    return "key" + "".join(p[:1].upper() + p[1:] for p in parts)

cps = [0] * len(names)
cm = key_zig[key_zig.index("const codepoint_map"):]
cm = cm[:cm.index("};")]
for ch, k in re.findall(r"\.\{ '(\\?.)', \.([a-z0-9_]+) \}", cm):
    c = {"\\t": 9, "\\'": 39, "\\\\": 92}.get(ch, None)
    c = ord(ch) if c is None else c
    if cps[index[k]] == 0:
        cps[index[k]] = c

kcode = [0] * len(names); kfinal = [0] * len(names); kmod = [0] * len(names)
kz = (g / "kitty.zig").read_text()
for k, code, final, mod in re.findall(r"\.\{ \.([a-z0-9_]+), (\d+), '(.)', (true|false) \}", kz):
    i = index[k]
    kcode[i] = int(code); kfinal[i] = ord(final); kmod[i] = 1 if mod == "true" else 0

def w3c_to_name(code):
    low = code.lower()
    if low in index:
        return low
    out = []
    for i, ch in enumerate(code):
        if ch.isupper() or ch.isdigit():
            if i > 0: out.append("_")
            out.append(ch.lower())
        else:
            out.append(ch)
    return "".join(out)

evdev = {}
kc = (g / "keycodes.zig").read_text()
for ev, code in re.findall(r"\.\{ 0x[0-9a-f]+, (0x[0-9a-f]+), 0x[0-9a-f]+, 0x[0-9a-f]+, 0x[0-9a-f]+, \"([A-Za-z0-9]*)\" \}", kc):
    ev = int(ev, 16)
    n = w3c_to_name(code)
    if ev and n in index and ev not in evdev:
        evdev[ev] = index[n]
top = max(evdev) + 1
evtable = [evdev.get(i, 0) for i in range(top)]

def lit(xs, per=24):
    return "\n    , ".join(", ".join(str(v) for v in xs[i:i + per]) for i in range(0, len(xs), per))

with open(here / "src/Vt/KeyTables.geng", "w") as f:
    consts = [camel(n) for n in names]
    f.write("module Vt.KeyTables exposing\n    ( " + "\n    , ".join(consts + ["codepoint", "kittyCode", "kittyFinal", "kittyModifier", "evdevKey", "keyCount"]) + "\n    )\n\n")
    f.write("{-| Generated by vt/gen-keys.py from libghostty-vt's key.zig, kitty.zig and\nkeycodes.zig: do not edit. %d keys, numbered as `GhosttyKey`; %d evdev codes. -}\n\n" % (len(names), len(evdev)))
    for i, n in enumerate(names):
        f.write("\n%s : Int\n%s =\n    %d\n\n" % (camel(n), camel(n), i))
    f.write("\nkeyCount : Int\nkeyCount =\n    %d\n\n" % len(names))
    for name, xs, doc in [
        ("codepointTable", cps, ""), ("kittyCodeTable", kcode, ""), ("kittyFinalTable", kfinal, ""),
        ("kittyModifierTable", kmod, ""), ("evdevTable", evtable, "")]:
        f.write("\n%s : Array Int\n%s =\n    [ %s\n    ]\n\n" % (name, name, lit(xs)))
    for fn, tab, doc in [
        ("codepoint", "codepointTable", "The code point a key stands for, 0 for none."),
        ("kittyCode", "kittyCodeTable", "The kitty protocol's number for a key, 0 for a key it has no entry for."),
        ("kittyFinal", "kittyFinalTable", "The final byte of a key's kitty sequence."),
        ("kittyModifier", "kittyModifierTable", "1 for a modifier key, which only `report all` sends."),
        ("evdevKey", "evdevTable", "The key for an evdev code (an X keycode less 8), 0 for none.")]:
        f.write("\n{-| %s -}\n%s : Int -> Int\n%s k =\n    Maybe.withDefault 0 (Array.get k %s)\n\n" % (doc, fn, fn, tab))
print(len(names), "keys,", len(evdev), "evdev codes,", sum(1 for c in kcode if c), "kitty entries")
