#!/usr/bin/env python3
"""Writes src/Vt/EucKrIndex.geng from WHATWG's index-euc-kr.txt (vt/data,
2024-09-18), the table Vt.Charset decodes and encodes EUC-KR and CP949 by
(docs/phase3-input.md V49): one literal of 126 leads by 190 trails, pointer
(lead - 0x81) * 190 + (trail - 0x41), 0 where the index has no code point.
"""
import pathlib
import subprocess

here = pathlib.Path(__file__).parent
table = [0] * (126 * 190)
for line in open(here / "data/index-euc-kr.txt"):
    if line.startswith("#") or not line.strip():
        continue
    p, cp = line.split()[:2]
    table[int(p)] = int(cp, 16)
with open(here / "src/Vt/EucKrIndex.geng", "w") as f:
    f.write("module Vt.EucKrIndex exposing (index)\n\n")
    f.write("{-| Generated by vt/gen-euckr.py from WHATWG's index-euc-kr.txt: do not\nedit. Pointer (lead - 0x81) * 190 + (trail - 0x41); 0 is no code point. -}\n\n\n")
    f.write("index : Array Int\nindex =\n    [ ")
    f.write("\n    , ".join(", ".join(str(v) for v in table[i:i + 19]) for i in range(0, len(table), 19)))
    f.write("\n    ]\n")
print(sum(1 for v in table if v), "code points")
# formatted as the rest of puritty (scripts/fmt.sh), so that a table made
# again is the same text
subprocess.run([str(here / "../scripts/fmt.sh"), str(here / "src/Vt/EucKrIndex.geng")], check=True, stdout=subprocess.DEVNULL)

