#!/usr/bin/env python3
"""Writes packages/tmux/src/Tmux/ColorNames.geng from tmux's colour.c:
the X11 color names tmux's colour_byname knows (puritty docs/tmux.md
TM65). The table is the same in tmux 3.6a and 3.8.

    color_names.py PATH/TO/tmux/colour.c
"""
import re
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "Tmux" / "ColorNames.geng"


def main():
    src = Path(sys.argv[1]).read_text()
    body = src[src.index("colour_byname(const char *name)"):]
    body = body[: body.index("};")]
    rows = re.findall(r'\{ "([^"]+)", 0x([0-9a-fA-F]{6}) \}', body)
    if len(rows) < 500:
        sys.exit(f"only {len(rows)} names found: is this tmux's colour.c?")
    lines = "\n".join(f"    {name.lower()}\t{rgb.lower()}" for name, rgb in rows)
    OUT.write_text(f'''module Tmux.ColorNames exposing (rgb)

{{-| The color names tmux takes besides its own (`colour_byname` in tmux's
`colour.c`, ISC licence, Nicholas Marriott and others): the X11 names,
`darkgoldenrod`, `gray70`, by any case. Generated by
`packages/tmux/tools/color_names.py`; do not edit. -}}

import Dict exposing (Dict)


{{-| A name's color as `0xRRGGBB`, as tmux reads it: `grey` or `gray`
alone is `0xbebebe`, followed by 0 to 100 a level of grey. -}}
rgb : String -> Maybe Int
rgb name0 =
    let
        name =
            String.toLower name0
    in
    if String.startsWith "grey" name || String.startsWith "gray" name then
        if String.count name == 4 then
            Just 0xBEBEBE

        else
            when String.toInt (String.dropFirst 4 name) is
                Just n ->
                    if n >= 0 && n <= 100 && String.all Char.isDigit (String.dropFirst 4 name) then
                        let
                            -- round(2.55 * n)
                            c =
                                (255 * n + 50) // 100
                        in
                        Just (c * 0x10000 + c * 0x100 + c)

                    else
                        Nothing

                Nothing ->
                    Nothing

    else
        Dict.get name table


table : Dict String Int
table =
    String.split "\\n" names
        |> Array.foldl
            (\\line acc ->
                when String.split "\\t" (String.trim line) is
                    [ n, hex ] ->
                        Dict.set n (String.foldl (\\c v -> v * 16 + hexDigit c) 0 hex) acc

                    _ ->
                        acc
            )
            Dict.empty


hexDigit : Char -> Int
hexDigit c =
    let
        code =
            Char.toCode c
    in
    if code >= 0x61 then code - 0x61 + 10 else code - 0x30


names : String
names =
    """
{lines}
    """
''')
    # formatted as the rest of puritty (scripts/fmt.sh), so that the table
    # made again is the same text
    subprocess.run([str(OUT.parents[4] / "scripts" / "fmt.sh"), str(OUT)], check=True, stdout=subprocess.DEVNULL)
    print(f"{OUT}: {len(rows)} names")


main()
