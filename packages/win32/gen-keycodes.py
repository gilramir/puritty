#!/usr/bin/env python3
"""Writes src/Ext/win32_keycodes.h (docs/windows.md WS5): for each Windows
scan code, the X keycode of the same key, from libghostty-vt's keycodes.zig
(vendor/ghostty, Chromium's table), whose rows give a key's code on each
platform. A key record's code on Windows is X's for the same key, so that
the application's `Keys.encode` reads it through `Vt.KeyTables.evdevKey` as
it reads Linux's.

The table is indexed by the scan code, plus 256 when Windows marks it
extended (0xE0); 0 where no key is known.
"""
import pathlib, re

here = pathlib.Path(__file__).parent
zig = (here / "../../vendor/ghostty/src/input/keycodes.zig").read_text()
raw = zig[zig.index("const raw_entries"):]
table = [0] * 512
rows = 0
for usb, evdev, xkb, win, mac, code in re.findall(
        r'\.\{ (0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+), "([A-Za-z0-9]*)" \}', raw):
    xkb, win = int(xkb, 16), int(win, 16)
    if not xkb or not win or xkb > 255:
        continue
    hi, lo = win >> 8, win & 0xFF
    if hi not in (0, 0xE0):
        continue
    i = lo + (256 if hi else 0)
    if not table[i]:
        table[i] = xkb
        rows += 1

out = here / "src/Ext/win32_keycodes.h"
with out.open("w") as f:
    f.write("/* Generated by packages/win32/gen-keycodes.py from libghostty-vt's\n"
            " * keycodes.zig: do not edit. A Windows scan code (plus 256 when it is\n"
            " * extended) to the X keycode of the same key, 0 for none; %d keys. */\n" % rows)
    f.write("static const unsigned char win32_xkeycode[512] = {\n")
    for k in range(0, 512, 16):
        f.write("    " + ", ".join("%3d" % v for v in table[k:k + 16]) + ",\n")
    f.write("};\n")
print(rows, "keys")
