#!/usr/bin/env python3
"""Writes src/Width.geng: the codepoint ranges that take two cells (East Asian
Width W and F) and those that take none (Mn, Me, Cf, and the Hangul medial and
final jamo), from Python's own unicodedata, for the probe's cost only. The real
package generates from UCD 17.0.0, the version core pins; Python's may be older.

usage: gen-width.py > src/Width.geng
"""
import sys
import unicodedata as u


def ranges(pred):
    out, start = [], None
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp < 0xE000:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def zero(c):
    cp = ord(c)
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF:
        return True
    return u.category(c) in ("Mn", "Me", "Cf")


wide = ranges(lambda c: u.east_asian_width(c) in ("W", "F"))
none = ranges(zero)


def arr(name, xs):
    body = "\n    , ".join(str(x) for x in xs)
    return f"{name} : Array Int\n{name} =\n    [ {body}\n    ]\n"


print(f"""module Width exposing (width)

{{-| Generated by gen-width.py from Python's unicodedata {u.unidata_version}: do not edit.
{len(wide)} wide ranges and {len(none)} zero-width ranges, each found by a binary search. -}}


{{-| How many cells a codepoint at or above 0x80 takes: 0, 1 or 2. -}}
width : Int -> Int
width cp =
    if find wideStarts wideEnds cp 0 (Array.length wideStarts - 1) then
        2

    else if find noneStarts noneEnds cp 0 (Array.length noneStarts - 1) then
        0

    else
        1


find : Array Int -> Array Int -> Int -> Int -> Int -> Bool
find starts ends cp lo hi =
    if lo > hi then
        False

    else
        let
            mid =
                (lo + hi) // 2

            s =
                Maybe.withDefault 0 (Array.get mid starts)
        in
        if cp < s then
            find starts ends cp lo (mid - 1)

        else if cp > Maybe.withDefault 0 (Array.get mid ends) then
            find starts ends cp (mid + 1) hi

        else
            True

""")
print(arr("wideStarts", [a for a, _ in wide]))
print()
print(arr("wideEnds", [b for _, b in wide]))
print()
print(arr("noneStarts", [a for a, _ in none]))
print()
print(arr("noneEnds", [b for _, b in none]))
