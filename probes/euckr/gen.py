#!/usr/bin/env python3
"""Writes the EUC-KR probe's index module and inputs (docs/phase3-input.md).

src/EucKrIndex.geng: WHATWG's index-euc-kr.txt (the CP949 superset, which
WHATWG decodes `euc-kr` as) as one dense literal, 126 leads by 190 trails,
0 where the index has no code point.

Inputs, in WORK (default ../../.harness-work/euckr):
  gitlog.euckr  harness/perf.py's gitlog.txt in CP949, what it cannot hold
                as '?'; gitlog.utf8 the same text decoded again, the bytes
                the core is fed after the filter
  ko.euckr      Korean ls-like lines: words of KS X 1001 syllables, a few
                Hanja and symbols, SGR colors; ko.utf8 the same in UTF-8
"""
import random, sys, pathlib

here = pathlib.Path(__file__).parent
work = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here / "../../.harness-work/euckr"
work.mkdir(parents=True, exist_ok=True)

table = [0] * (126 * 190)
for line in open(here / "../../vt/data/index-euc-kr.txt"):
    if line.startswith("#") or not line.strip():
        continue
    p, cp = line.split()[:2]
    table[int(p)] = int(cp, 16)
with open(here / "src/EucKrIndex.geng", "w") as f:
    f.write("module EucKrIndex exposing (index)\n\n")
    f.write("{-| Generated by probes/euckr/gen.py from WHATWG's index-euc-kr.txt: do not\nedit. Pointer (lead - 0x81) * 190 + (trail - 0x41); 0 is no code point. -}\n\n\n")
    f.write("index : Array Int\nindex =\n    [ ")
    f.write("\n    , ".join(", ".join(str(v) for v in table[i:i + 19]) for i in range(0, len(table), 19)))
    f.write("\n    ]\n")

git = (here / "../../.harness-work/perf/inputs/gitlog.txt").read_bytes().decode("utf-8", "replace")
cp = git.encode("cp949", "replace")
(work / "gitlog.euckr").write_bytes(cp)
(work / "gitlog.utf8").write_bytes(cp.decode("cp949").encode())

rng = random.Random(7)
syll = [c for c in (bytes([a, b]).decode("euc-kr") for a in range(0xB0, 0xC9) for b in range(0xA1, 0xFF))]
hanja = [bytes([a, b]).decode("euc-kr") for a in range(0xCA, 0xFE) for b in range(0xA1, 0xFF)]
sym = "①②③★○●◎◇□■△▲→←↑↓─│┌┐└┘├┤"
lines = []
size = 0
while size < 24_000_000:
    words = []
    for _ in range(rng.randint(3, 9)):
        w = "".join(rng.choice(syll) for _ in range(rng.randint(1, 5)))
        r = rng.random()
        if r < 0.05: w += rng.choice(hanja)
        elif r < 0.1: w = rng.choice(sym) + w
        elif r < 0.3: w = f"\x1b[{rng.choice([1, 31, 32, 34, 36])}m{w}\x1b[0m"
        elif r < 0.45: w = w + "_" + str(rng.randint(1, 999)) + ".txt"
        words.append(w)
    line = "  ".join(words) + "\r\n"
    b = line.encode("cp949")
    lines.append(line)
    size += len(b)
text = "".join(lines)
(work / "ko.euckr").write_bytes(text.encode("cp949"))
(work / "ko.utf8").write_bytes(text.encode())
for n in ["gitlog.euckr", "gitlog.utf8", "ko.euckr", "ko.utf8"]:
    print(n, (work / n).stat().st_size)
