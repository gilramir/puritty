#!/usr/bin/env python3
"""Every piece of puritty that comes from elsewhere has its notice
(THIRD-PARTY-NOTICES.md, LICENSES/).

The notices' `paths` block maps patterns to licence files (`own` for
puritty's own). The check fails on:

- a vendored folder (a folder inside a package's `src/Ext/`, but for
  `include`), a patch (`packages/*/patches/*`), or a generated file (one
  whose first lines say "Generated by" or "Written by") that no pattern
  covers;
- a library source a build script fetches (`$(src NAME)`) with no
  `src:NAME` line;
- a pattern that matches no file in git;
- a licence file named that is not in LICENSES/, or one in LICENSES/ that
  nothing names.

    scripts/notices.py
"""
import fnmatch
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD-PARTY-NOTICES.md"
LICENSES = ROOT / "LICENSES"
BUILDS = [ROOT / "app" / "distro" / "build-libs.sh", ROOT / "packages" / "win32" / "build-text-libs.sh"]
# not puritty's source: records, documents, the website, and these files
SKIP = ("corpus/", "LICENSES/", "site/", "THIRD-PARTY-NOTICES.md", "scripts/notices.py")


def main():
    text = NOTICES.read_text()
    block = re.search(r"```paths\n(.*?)```", text, re.S)
    if not block:
        print("THIRD-PARTY-NOTICES.md has no ```paths block")
        return 1
    rows = []
    for line in block.group(1).splitlines():
        if line.strip():
            pattern, files = line.split("\t", 1)
            rows.append((pattern, files.split()))

    tracked = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split("\n")
    tracked = [t for t in tracked if t]
    problems = []

    # licence files: named ones exist, and each one is named
    named = {f for _, files in rows for f in files if f != "own"} | set(re.findall(r"[(,] `([A-Za-z0-9.-]+\.txt)`", text))
    for f in sorted(named):
        if not (LICENSES / f).exists():
            problems.append(f"MISSING  LICENSES/{f}")
    for f in sorted(p.name for p in LICENSES.glob("*.txt")):
        if f not in named:
            problems.append(f"UNUSED   LICENSES/{f}")

    # each file pattern matches something
    def covered(path):
        return any(not p.startswith(("src:", "lib:")) and fnmatch.fnmatch(path, p) for p, _ in rows)

    for p, _ in rows:
        if not p.startswith(("src:", "lib:")) and not any(fnmatch.fnmatch(t, p) for t in tracked):
            problems.append(f"STALE    {p}: matches no file")

    # what comes from elsewhere
    origins = set()
    for t in tracked:
        if t.startswith(SKIP) or t.startswith("docs/") and not t.startswith("docs/images/"):
            continue
        m = re.match(r"packages/[^/]+/src/Ext/([^/]+)/", t)
        if m and m.group(1) != "include":
            origins.add(t)
        elif re.match(r"packages/[^/]+/patches/", t):
            origins.add(t)
        elif (ROOT / t).is_file() and (ROOT / t).suffix in (".geng", ".c", ".h", ".py", ".txt", ".sh"):
            head = "\n".join((ROOT / t).read_text(errors="replace").splitlines()[:25])
            if re.search(r"\b(Generated|Written) by\b", head):
                origins.add(t)
    for t in sorted(origins):
        if not covered(t):
            problems.append(f"UNLISTED {t}")

    for b in BUILDS:
        for name in sorted(set(re.findall(r"\$\(src ([a-z0-9-]+)\)", b.read_text()))):
            if not any(p == "src:" + name for p, _ in rows):
                problems.append(f"UNLISTED src:{name} ({b.relative_to(ROOT)})")

    for p in problems:
        print(p)
    print(f"{len(rows)} patterns, {len(origins)} files from elsewhere or generated, {len(named)} licences: {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
