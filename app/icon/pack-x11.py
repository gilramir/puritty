#!/usr/bin/env python3
"""Writes packages/x11/src/Ext/puritty_icon.h from png/<size>.png: the
window's _NET_WM_ICON, each size its width, its height and its pixels as
ARGB, one 32-bit value each, as the property holds them. 16 to 64 px:
the property goes to the X server with every window, over ssh -X too, so
the 256 px picture (256 KB) is left to the desktop file's icons."""
import struct
import zlib
from pathlib import Path

here = Path(__file__).resolve().parent
out = here.parent.parent / "packages" / "x11" / "src" / "Ext" / "puritty_icon.h"
SIZES = [16, 24, 32, 48, 64]


def rgba(path):
    data = path.read_bytes()
    i, idat = 8, b""
    while i < len(data):
        n, = struct.unpack(">I", data[i:i + 4])
        kind, body = data[i + 4:i + 8], data[i + 8:i + 8 + n]
        if kind == b"IHDR":
            w, h, depth, colour, _, _, lace = struct.unpack(">IIBBBBB", body)
            assert (depth, colour, lace) == (8, 6, 0), f"{path}: not 8-bit RGBA"
        elif kind == b"IDAT":
            idat += body
        i += 12 + n
    raw, stride, rows, prev = zlib.decompress(idat), w * 4, [], bytearray(w * 4)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = line[x - 4] if x >= 4 else 0
            b = prev[x]
            c = prev[x - 4] if x >= 4 else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line))
        prev = line
    return w, h, b"".join(rows)


values = []
for s in SIZES:
    w, h, px = rgba(here / "png" / f"{s}.png")
    values += [w, h]
    for i in range(0, len(px), 4):
        r, g, b, a = px[i:i + 4]
        values.append((a << 24) | (r << 16) | (g << 8) | b)
lines = [", ".join(f"0x{v:08x}" for v in values[i:i + 8]) for i in range(0, len(values), 8)]
out.write_text(
    "/* Generated by app/icon/pack-x11.py from app/icon/png: do not edit.\n"
    " * The window's _NET_WM_ICON (docs/windows.md WS25): for each size, its\n"
    f" * width, its height, and its pixels as ARGB. Sizes {', '.join(map(str, SIZES))}. */\n"
    "static const uint32_t puritty_icon[] = {\n    " + ",\n    ".join(lines) + "\n};\n")
print(f"{out.name}: {len(values)} values")
